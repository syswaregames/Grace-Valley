#include "grace/world.hpp"

#ifdef NDEBUG
#undef NDEBUG // Keep these rule checks active in Release builds.
#endif
#include <cassert>
#include <iostream>
#include <sstream>

int main() {
    grace::World world;
    assert(world.terrain(20, 4) == grace::Terrain::water);
    assert(world.placement_error(20, 4, grace::Tile::road) ==
           grace::PlacementError::needs_connection);
    assert(world.placement_error(20, 4, grace::Tile::chapel) ==
           grace::PlacementError::water);
    assert(world.terrain(17, 10) == grace::Terrain::woods);
    assert(world.cost_at(17, 10, grace::Tile::road) == grace::World::cost(grace::Tile::road) + 10);
    const auto start = world.snapshot();
    assert(start.week == 1);
    assert(start.capacity == 0);
    assert(start.power_capacity == 0);
    assert(start.power_demand == 1);
    assert(start.commuters == 0 && start.congested_roads == 0);
    assert(!world.is_powered(10, 7));
    assert(start.weekly_income == 10);
    assert(start.weekly_upkeep == 8);
    assert(start.weekly_income == start.grant_income + start.giving_income);
    assert(start.weekly_upkeep == start.building_upkeep + start.service_upkeep +
                                  start.community_upkeep);
    grace::World bridge;
    for (int x : {16, 17}) assert(bridge.place(x, 8, grace::Tile::road));
    for (int y : {7, 6, 5, 4}) assert(bridge.place(17, y, grace::Tile::road));
    assert(bridge.cost_at(18, 4, grace::Tile::road) == 25);
    const int before_bridge = bridge.snapshot().treasury;
    for (int x = 18; x <= 22; ++x)
        assert(bridge.place(x, 4, grace::Tile::road));
    assert(bridge.snapshot().treasury == before_bridge - 125);
    assert(bridge.terrain(20, 4) == grace::Terrain::water);
    assert(bridge.is_connected(20, 4));
    assert(bridge.place(23, 4, grace::Tile::road));
    assert(bridge.is_connected(23, 4));
    assert(bridge.place(23, 3, grace::Tile::power_plant));
    assert(bridge.place(23, 5, grace::Tile::residential_zone));
    assert(bridge.is_powered(23, 5));
    assert(bridge.is_powered(10, 7));
    bridge.advance_week();
    assert(bridge.tile(23, 5) == grace::Tile::home);
    std::stringstream bridge_file;
    assert(bridge.save(bridge_file));
    auto restored_bridge = grace::World::load(bridge_file);
    assert(restored_bridge && restored_bridge->is_connected(23, 4));
    assert(restored_bridge->terrain(20, 4) == grace::Terrain::water);
    assert(restored_bridge->tile(20, 4) == grace::Tile::road);
    assert(bridge.remove(20, 4));
    assert(!bridge.is_connected(23, 4));
    assert(bridge.snapshot().power_capacity == 0);
    assert(bridge.place(20, 4, grace::Tile::road));
    assert(bridge.is_connected(23, 4));
    assert(bridge.is_powered(10, 7));
    grace::World power;
    assert(power.place(11, 9, grace::Tile::residential_zone));
    assert(!power.is_powered(11, 9));
    power.advance_week();
    assert(power.tile(11, 9) == grace::Tile::residential_zone);
    assert(power.place(13, 9, grace::Tile::power_plant));
    assert(power.snapshot().power_capacity == 12);
    assert(power.is_powered(11, 9));
    grace::World commute;
    assert(commute.place(15, 7, grace::Tile::power_plant));
    assert(commute.place(9, 7, grace::Tile::home));
    assert(commute.place(8, 7, grace::Tile::home));
    assert(commute.place(13, 9, grace::Tile::industrial_zone));
    assert(commute.place(14, 9, grace::Tile::commercial_zone));
    assert(commute.place(15, 9, grace::Tile::commercial_zone));
    for (int week = 0; week < 12; ++week) commute.advance_week();
    assert(commute.snapshot().commuters >= 8);
    assert(commute.traffic_at(12, 8) > commute.road_capacity(12, 8));
    assert(commute.snapshot().congested_roads > 0);
    grace::World quality_town = commute;
    assert(quality_town.remove(15, 9));
    const auto congested = quality_town.snapshot();
    assert(congested.congested_roads > 0);
    for (int y = 0; y < grace::World::height; ++y)
        for (int x = 0; x < grace::World::width; ++x)
            if (quality_town.traffic_at(x, y) > quality_town.road_capacity(x, y))
                assert(quality_town.upgrade_road(x, y));
    const auto relieved = quality_town.snapshot();
    assert(relieved.congested_roads == 0);
    assert(relieved.city_score > congested.city_score);
    assert(relieved.residential_demand > congested.residential_demand);
    assert(relieved.commercial_demand > congested.commercial_demand);
    assert(relieved.industrial_demand > congested.industrial_demand);
    const int jams_before_upgrade = commute.snapshot().congested_roads;
    const int funds_before_upgrade = commute.snapshot().treasury;
    const int upkeep_before_upgrade = commute.snapshot().weekly_upkeep;
    const int score_before_upgrade = commute.snapshot().city_score;
    const int homes_demand_before_upgrade = commute.snapshot().residential_demand;
    const int shops_demand_before_upgrade = commute.snapshot().commercial_demand;
    const int industry_demand_before_upgrade = commute.snapshot().industrial_demand;
    assert(commute.upgrade_road(12, 8));
    assert(commute.road_level(12, 8) == 1);
    assert(commute.road_capacity(12, 8) == 14);
    assert(commute.next_road_upgrade_cost(12, 8) == 35);
    assert(commute.snapshot().treasury == funds_before_upgrade - 20);
    assert(commute.snapshot().weekly_upkeep == upkeep_before_upgrade + 1);
    assert(commute.snapshot().congested_roads == jams_before_upgrade - 1);
    assert(commute.snapshot().city_score > score_before_upgrade);
    assert(commute.snapshot().residential_demand > homes_demand_before_upgrade);
    assert(commute.snapshot().commercial_demand >= shops_demand_before_upgrade);
    assert(commute.snapshot().industrial_demand >= industry_demand_before_upgrade);
    std::stringstream saved_commute;
    assert(commute.save(saved_commute));
    auto restored_commute = grace::World::load(saved_commute);
    assert(restored_commute);
    assert(restored_commute->snapshot().week == commute.snapshot().week);
    assert(restored_commute->snapshot().treasury == commute.snapshot().treasury);
    assert(restored_commute->snapshot().congested_roads == commute.snapshot().congested_roads);
    assert(restored_commute->snapshot().city_score == commute.snapshot().city_score);
    assert(restored_commute->traffic_at(12, 8) == commute.traffic_at(12, 8));
    assert(restored_commute->is_upgraded_road(12, 8));
    std::string legacy_text = saved_commute.str();
    legacy_text.replace(legacy_text.find("GRACE_VALLEY_WORLD 2"),
                        sizeof("GRACE_VALLEY_WORLD 2") - 1, "GRACE_VALLEY_WORLD 1");
    std::stringstream legacy_save(legacy_text);
    auto restored_legacy = grace::World::load(legacy_save);
    assert(restored_legacy && restored_legacy->road_level(12, 8) == 1);
    commute.advance_week();
    restored_commute->advance_week();
    assert(restored_commute->snapshot().treasury == commute.snapshot().treasury);
    assert(restored_commute->snapshot().population == commute.snapshot().population);
    assert(restored_commute->snapshot().happiness == commute.snapshot().happiness);
    std::stringstream unsupported("GRACE_VALLEY_WORLD 999");
    assert(!grace::World::load(unsupported));
    std::stringstream truncated("GRACE_VALLEY_WORLD 1\n1 0");
    assert(!grace::World::load(truncated));
    grace::World policy_save;
    assert(policy_save.place(13, 9, grace::Tile::power_plant));
    policy_save.set_giving_policy(grace::GivingPolicy::ambitious);
    policy_save.set_service_budget(grace::ServiceBudget::generous);
    policy_save.set_tax_policy(grace::TaxPolicy::high);
    policy_save.set_care_priority(true);
    policy_save.advance_week();
    policy_save.advance_week();
    assert(policy_save.host_event(grace::EventKind::gathering) == grace::EventError::none);
    std::stringstream policy_file;
    assert(policy_save.save(policy_file));
    auto restored_policy = grace::World::load(policy_file);
    assert(restored_policy);
    assert(restored_policy->snapshot().giving_policy == grace::GivingPolicy::ambitious);
    assert(restored_policy->snapshot().service_budget == grace::ServiceBudget::generous);
    assert(restored_policy->snapshot().tax_policy == grace::TaxPolicy::high);
    assert(restored_policy->snapshot().care_first);
    assert(restored_policy->snapshot().event_weeks_left == 2);
    assert(restored_policy->snapshot().event_cooldown == policy_save.snapshot().event_cooldown);
    assert(restored_policy->terrain(20, 4) == grace::Terrain::water);
    policy_save.advance_week();
    restored_policy->advance_week();
    assert(restored_policy->snapshot().treasury == policy_save.snapshot().treasury);
    assert(restored_policy->household_needs(10, 7).care ==
           policy_save.household_needs(10, 7).care);
    const int avenue_funds = commute.snapshot().treasury;
    const int avenue_upkeep = commute.snapshot().weekly_upkeep;
    assert(commute.upgrade_road(12, 8));
    assert(commute.road_level(12, 8) == 2);
    assert(commute.road_capacity(12, 8) == 24);
    assert(commute.snapshot().treasury == avenue_funds - 35);
    assert(commute.snapshot().weekly_upkeep == avenue_upkeep + 2);
    assert(commute.next_road_upgrade_cost(12, 8) == 55);
    const int boulevard_funds = commute.snapshot().treasury;
    const int boulevard_upkeep = commute.snapshot().weekly_upkeep;
    assert(commute.upgrade_road(12, 8));
    assert(commute.road_level(12, 8) == 3);
    assert(commute.road_capacity(12, 8) == 36);
    assert(commute.snapshot().treasury == boulevard_funds - 55);
    assert(commute.snapshot().weekly_upkeep == boulevard_upkeep + 3);
    assert(commute.next_road_upgrade_cost(12, 8) == 0);
    assert(!commute.upgrade_road(12, 8));
    std::stringstream arterial_save;
    assert(commute.save(arterial_save));
    auto restored_arterial = grace::World::load(arterial_save);
    assert(restored_arterial && restored_arterial->road_level(12, 8) == 3);
    assert(commute.upgrade_road(11, 8));
    assert(commute.remove(11, 8));
    assert(!commute.is_upgraded_road(11, 8));
    assert(commute.traffic_at(12, 8) == 0);
    power.advance_week();
    assert(power.tile(11, 9) == grace::Tile::home);
    assert(power.is_powered(11, 9));
    assert(power.snapshot().power_demand == 2);
    assert(power.remove(13, 8));
    assert(power.snapshot().power_capacity == 0);
    assert(!power.is_powered(11, 9));
    assert(power.snapshot().unpowered_buildings == 2);
    assert(power.snapshot().capacity == 0);
    assert(power.place(13, 8, grace::Tile::road));
    assert(power.snapshot().power_capacity == 12);
    assert(power.is_powered(11, 9));
    grace::World forecast;
    const auto first_week = forecast.snapshot();
    forecast.advance_week();
    assert(forecast.snapshot().treasury == first_week.treasury +
           first_week.weekly_income - first_week.weekly_upkeep);
    grace::World lean_budget;
    grace::World generous_budget;
    assert(lean_budget.place(11, 9, grace::Tile::pantry));
    assert(generous_budget.place(11, 9, grace::Tile::pantry));
    lean_budget.set_service_budget(grace::ServiceBudget::lean);
    generous_budget.set_service_budget(grace::ServiceBudget::generous);
    assert(lean_budget.snapshot().service_upkeep <
           generous_budget.snapshot().service_upkeep);
    lean_budget.advance_week();
    generous_budget.advance_week();
    assert(generous_budget.household_needs(10, 7).care >
           lean_budget.household_needs(10, 7).care);
    grace::World gentle_giving;
    grace::World ambitious_giving;
    assert(gentle_giving.place(13, 9, grace::Tile::power_plant));
    assert(ambitious_giving.place(13, 9, grace::Tile::power_plant));
    gentle_giving.set_giving_policy(grace::GivingPolicy::gentle);
    ambitious_giving.set_giving_policy(grace::GivingPolicy::ambitious);
    gentle_giving.advance_week();
    ambitious_giving.advance_week();
    assert(ambitious_giving.snapshot().giving_income >
           gentle_giving.snapshot().giving_income);
    assert(ambitious_giving.household_needs(10, 7).belonging <
           gentle_giving.household_needs(10, 7).belonging);
    grace::World zoned;
    assert(zoned.place(15, 7, grace::Tile::power_plant));
    assert(zoned.place(0, 0, grace::Tile::residential_zone));
    assert(!zoned.place(20, 4, grace::Tile::commercial_zone));
    assert(zoned.place(11, 9, grace::Tile::residential_zone));
    zoned.advance_week();
    assert(zoned.tile(0, 0) == grace::Tile::residential_zone);
    assert(zoned.tile(11, 9) == grace::Tile::home);
    assert(zoned.snapshot().capacity == 8);
    grace::World business;
    assert(business.place(14, 9, grace::Tile::power_plant));
    assert(business.place(11, 9, grace::Tile::commercial_zone));
    assert(business.place(13, 9, grace::Tile::industrial_zone));
    assert(business.snapshot().commercial_demand < 25);
    business.advance_week();
    assert(business.tile(11, 9) == grace::Tile::commercial_zone);
    assert(business.tile(13, 9) == grace::Tile::industrial_zone);
    business.advance_week();
    assert(business.tile(11, 9) == grace::Tile::commercial);
    assert(business.tile(13, 9) == grace::Tile::industrial_zone);
    business.advance_week();
    assert(business.tile(13, 9) == grace::Tile::industrial);
    assert(business.snapshot().jobs == 10);
    assert(business.snapshot().tax_income > 0);
    grace::World no_business;
    no_business.advance_week();
    no_business.advance_week();
    assert(business.snapshot().residential_demand >
           no_business.snapshot().residential_demand);
    grace::World park_demand;
    assert(park_demand.place(13, 9, grace::Tile::park));
    assert(park_demand.snapshot().residential_demand > start.residential_demand);
    const auto normal_tax = business.snapshot();
    business.set_tax_policy(grace::TaxPolicy::low);
    assert(business.snapshot().tax_income < normal_tax.tax_income);
    assert(business.snapshot().commercial_demand > normal_tax.commercial_demand);
    const auto low_tax = business.snapshot();
    business.set_tax_policy(grace::TaxPolicy::high);
    assert(business.snapshot().tax_income > normal_tax.tax_income);
    assert(business.snapshot().industrial_demand < low_tax.industrial_demand);
    assert(business.remove(11, 8));
    assert(business.snapshot().shops == 0);
    assert(business.snapshot().jobs == 6);
    grace::World vacant;
    assert(vacant.place(13, 9, grace::Tile::power_plant));
    assert(vacant.place(11, 9, grace::Tile::commercial_zone));
    vacant.set_tax_policy(grace::TaxPolicy::high);
    for (int week = 0; week < 6; ++week) vacant.advance_week();
    assert(vacant.tile(11, 9) == grace::Tile::commercial_zone);
    assert(vacant.snapshot().commercial_demand < 25);
    vacant.set_tax_policy(grace::TaxPolicy::low);
    assert(vacant.snapshot().commercial_demand >= 25);
    vacant.advance_week();
    assert(vacant.tile(11, 9) == grace::Tile::commercial);
    assert(!world.place(-1, 0, grace::Tile::road));
    assert(!world.place(0, 0, grace::Tile::home));
    assert(world.placement_error(0, 0, grace::Tile::road) ==
           grace::PlacementError::needs_connection);
    assert(!world.remove(12, 8)); // The starting chapel's road anchors the network.
    assert(world.place(9, 7, grace::Tile::home));
    assert(world.snapshot().capacity == 0);
    assert(world.snapshot().treasury == start.treasury - 30);
    assert(world.place(13, 9, grace::Tile::power_plant));
    assert(world.snapshot().capacity == 8);
    assert(world.home_has_service(10, 7, grace::Tile::chapel));
    assert(!world.home_has_service(10, 7, grace::Tile::pantry));
    assert(world.would_serve_home(grace::Tile::pantry, 15, 7, 10, 7));
    assert(!world.would_serve_home(grace::Tile::pantry, 15, 7, 9, 7));
    assert(world.coverage_change_if_placed(grace::Tile::pantry, 15, 7) == 1);
    assert(world.place(11, 9, grace::Tile::pantry));
    assert(world.snapshot().served_homes == 2);
    assert(world.homes_with_service(grace::Tile::pantry) == 2);
    world.advance_week();
    assert(world.snapshot().week == 2);
    assert(world.snapshot().population > 0);
    assert(world.remove(11, 9));
    assert(world.snapshot().served_homes == 0);
    assert(world.remove(11, 8));
    assert(!world.is_connected(10, 8));
    assert(world.snapshot().connected_homes == 0);
    assert(world.snapshot().capacity == 0);
    assert(!world.home_has_service(10, 7, grace::Tile::chapel));
    assert(world.place(12, 9, grace::Tile::road));
    assert(world.place(11, 9, grace::Tile::road));
    assert(world.place(10, 9, grace::Tile::road));
    assert(world.is_connected(10, 8));
    assert(world.snapshot().connected_homes == 2);
    grace::World repair;
    assert(repair.remove(11, 8));
    assert(!repair.is_connected(10, 8));
    assert(repair.can_place(10, 9, grace::Tile::road));
    assert(!repair.can_place(10, 7, grace::Tile::home));
    assert(repair.place(10, 9, grace::Tile::road));
    assert(!repair.is_connected(10, 9));
    assert(repair.place(11, 9, grace::Tile::road));
    assert(!repair.is_connected(11, 9));
    assert(repair.place(12, 9, grace::Tile::road));
    assert(repair.is_connected(10, 8));
    grace::World terrain_world;
    assert(terrain_world.place(16, 8, grace::Tile::road));
    assert(terrain_world.place(17, 8, grace::Tile::road));
    assert(terrain_world.place(17, 9, grace::Tile::road));
    const int before_woods = terrain_world.snapshot().treasury;
    assert(terrain_world.place(17, 10, grace::Tile::road));
    assert(terrain_world.snapshot().treasury == before_woods - 15);
    assert(terrain_world.terrain(17, 10) == grace::Terrain::grass);

    grace::World staffed;
    assert(staffed.place(11, 9, grace::Tile::pantry));
    assert(staffed.place(13, 7, grace::Tile::chapel));
    assert(staffed.snapshot().active_chapels == 2);
    assert(staffed.snapshot().active_pantries == 0);
    assert(!staffed.home_has_service(10, 7, grace::Tile::pantry));
    assert(staffed.coverage_change_if_placed(grace::Tile::pantry, 10, 9) == 0);
    assert(!staffed.would_serve_home(grace::Tile::pantry, 10, 9, 10, 7));
    staffed.set_care_priority(true);
    assert(staffed.snapshot().active_chapels == 1);
    assert(staffed.snapshot().active_pantries == 1);
    assert(staffed.home_has_service(10, 7, grace::Tile::pantry));
    grace::World shifted_staff;
    assert(shifted_staff.place(9, 7, grace::Tile::home));
    assert(shifted_staff.place(11, 9, grace::Tile::pantry));
    shifted_staff.set_care_priority(true);
    assert(shifted_staff.coverage_change_if_placed(grace::Tile::pantry, 15, 7) == -1);

    grace::World without_care;
    grace::World with_care;
    assert(with_care.place(11, 9, grace::Tile::pantry));
    for (int week = 0; week < 4; ++week) {
        without_care.advance_week();
        with_care.advance_week();
    }
    assert(with_care.household_needs(10, 7).care >
           without_care.household_needs(10, 7).care);
    assert(with_care.snapshot().care > without_care.snapshot().care);

    grace::World events;
    assert(events.can_host_event() == grace::EventError::no_people);
    assert(events.place(13, 9, grace::Tile::power_plant));
    events.advance_week();
    assert(events.can_host_event() == grace::EventError::none);
    const int before_event = events.snapshot().treasury;
    assert(events.host_event() == grace::EventError::none);
    assert(events.snapshot().treasury == before_event - 30);
    assert(events.snapshot().event_weeks_left == 2);
    assert(events.snapshot().event_cooldown == 6);
    assert(events.host_event() == grace::EventError::cooldown);
    events.advance_week();
    assert(events.snapshot().event_weeks_left == 1);
    assert(events.snapshot().event_cooldown == 5);
    events.advance_week();
    assert(events.snapshot().event_weeks_left == 0);
    grace::World food_drives;
    grace::World no_events;
    assert(food_drives.place(13, 9, grace::Tile::power_plant));
    assert(no_events.place(13, 9, grace::Tile::power_plant));
    for (int week = 0; week < 24; ++week) {
        if (food_drives.can_host_event(grace::EventKind::food_drive) ==
            grace::EventError::none)
            assert(food_drives.host_event(grace::EventKind::food_drive) ==
                   grace::EventError::none);
        food_drives.advance_week();
        no_events.advance_week();
    }
    assert(food_drives.snapshot().events_hosted >= 3);
    assert(food_drives.snapshot().care > no_events.snapshot().care);
    assert(food_drives.snapshot().care >= 50);
    grace::World busy_services;
    assert(busy_services.place(11, 9, grace::Tile::pantry));
    assert(busy_services.place(13, 9, grace::Tile::power_plant));
    busy_services.advance_week();
    assert(busy_services.can_host_event() == grace::EventError::insufficient_volunteers);
    assert(busy_services.place(9, 7, grace::Tile::home));
    for (int week = 0; week < 3; ++week) busy_services.advance_week();
    assert(busy_services.can_host_event() == grace::EventError::none);
    std::cout << "world tests passed\n";
}
